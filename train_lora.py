#!/usr/bin/env python3
"""
Module 2: Memory-Optimized Stable Diffusion 1.5 LoRA Training Engine
===================================================================
Part of an Open-Source Image-to-Cartoon-Video Generation Pipeline.

This engine trains Low-Rank Adaptation (LoRA) adapters on Stable Diffusion 1.5
UNet attention layers (to_k, to_q, to_v, to_out.0). It is engineered for zero-cost
cloud GPU environments (e.g., Google Colab or Kaggle T4 GPUs with 15–16 GB VRAM):
  - 8-bit AdamW optimizer (bitsandbytes) with graceful fallback to standard AdamW.
  - Native PyTorch 2.x SDPA and optional xFormers memory-efficient attention.
  - Gradient checkpointing and configurable gradient accumulation.
  - fp16 / bf16 mixed-precision training via Hugging Face Accelerate.
  - Frozen VAE and Text Encoder (with optional Text Encoder LoRA fine-tuning).
  - On-the-fly random flip and color jitter augmentations.
  - Periodic style-convergence validation and standalone .safetensors checkpointing.

Author: Senior Generative AI Engineer / PyTorch Specialist
License: Apache 2.0
"""

